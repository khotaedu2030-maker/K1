-- تشخيصي فقط — قراءة بحتة، لا يعدّل أي بيانات، لم يُنفَّذ تلقائيًا.
-- "مكتملة" أصبحت حالة مشتقة (status='open' و seats_available<=0)، لا قيمة تُخزَّن. هذا الملف
-- يكشف أي مجموعات لا تزال محفوظة فعليًا بحالة status='full' القديمة من قبل هذا التصميم.

select id, title, grade_band, product, capacity, status, created_at
from cohorts
where status = 'full'
order by title;

-- إن أظهر الاستعلام أعلاه أي صفوف: التنظيف اليدوي المقترح (لا تُنفِّذه تلقائيًا، راجع كل صف
-- أولًا) هو تحويلها إلى 'open' — عندها يصبح ظهورها كـ"مكتملة" مشتقًا تلقائيًا من
-- seats_available بدل قيمة مخزَّنة ثابتة، متوافقًا مع كل الدوال والواجهة الحالية:
--
-- update cohorts set status = 'open' where status = 'full';
